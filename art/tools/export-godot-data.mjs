// Exports the procedural art data (art/sprites.ts, pipeline/pixel-font.ts, the pipeline-owned
// masks in pipeline/texture-baker.ts, pipeline/fx-data.json) to game/data/art.json for the
// Godot baker (game/scripts/art/baker.gd). The TypeScript files stay the authoring source;
// run this after art/tools/build-sprites.mjs. Node 23.6+ strips the TS types natively.
//   node art/tools/export-godot-data.mjs
import { writeFileSync, readFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const art = await import(new URL("art/sprites.ts", root));
const font = await import(new URL("pipeline/pixel-font.ts", root));
const baker = await import(new URL("pipeline/texture-baker.ts", root));
const fx = JSON.parse(readFileSync(new URL("pipeline/fx-data.json", root), "utf8"));
// v2 sprites are authored straight as grids in art/v2-sprites.json (same palette and format).
const v2 = JSON.parse(readFileSync(new URL("art/v2-sprites.json", root), "utf8"));
const out = {
  _doc: "GENERATED by art/tools/export-godot-data.mjs from art/sprites.ts, pipeline/pixel-font.ts, pipeline/texture-baker.ts, pipeline/fx-data.json and art/v2-sprites.json. Do not edit.",
  palette: art.PALETTE,
  skyBands: art.SKY_BANDS,
  uiTheme: art.UI_THEME,
  meta: art.SPRITE_META,
  sprites: { ...baker.PIPELINE_SPRITES, ...art.SPRITES, ...v2.sprites },
  font: {
    metrics: font.FONT_METRICS,
    outline: font.FONT_OUTLINE,
    variants: font.FONT_VARIANTS,
    aliases: font.FONT_ALIASES,
    fallback: font.FONT_FALLBACK,
    glyphs: font.FONT_GLYPHS,
  },
  fx,
};
writeFileSync(new URL("game/data/art.json", root), JSON.stringify(out));
console.log(`art.json: ${Object.keys(out.sprites).length} sprites, ${Object.keys(out.font.glyphs).length} glyphs, ${Object.keys(out.palette).length} palette chars`);
