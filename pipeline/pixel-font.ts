// The fork's procedural 5×7 pixel font. PURE DATA: no imports, no Phaser, no functions.
// Owner: Technical Artist (pipeline/). Consumer: pipeline/texture-baker.ts, which bakes these
// grids into the shared atlas and registers three BitmapText fonts at boot.
//
// GLYPH GRIDS
//   FONT_GLYPHS[char] is 7 strings of 5 chars. '#' = ink, '.' = empty. Row 6 is the baseline row
//   (caps and digits sit on it). Lowercase exists for completeness (ASCII 32–126 is covered), but
//   the UX rule is "all rendered text is UPPERCASE" (ux/number-and-copy.md §1), so the game draws caps.
//   Extra glyphs the copy needs: × (U+00D7, centred, smaller than X) and → (U+2192).
//   Digit 0 is slashed so "10" never reads as "1O" next to letters.
//
// ADDING A GLYPH (a content task, no re-rasterization fire drill):
//   add one entry below, save, and reload. The baker packs every key it finds, and
//   `node pipeline/verify-pipeline.mjs` checks shape, width and coverage of ux/ui-strings.json.
//
// METRICS (font px; multiply by the integer render scale s for logical px)
//   advance 6 (5 ink + 1 gap), so the width of n chars = 6·s·n − s  (matches ux/hud-layout.md §0).
//   line height 9 (7 + 2 gap). BitmapText size = 7, so `fontSize = 7·s` renders at exactly ×s.

export const FONT_METRICS = {
  glyphW: 5,
  glyphH: 7,
  /** Pixels from one glyph origin to the next (5 ink + 1 gap). Monospace: every glyph shares it. */
  advance: 6,
  letterSpacing: 1,
  /** 7 rows + 2 gap rows. UX pitches (20/28/36 px at ×2/×3/×4) are set per line by the developer. */
  lineHeight: 9,
  /** The BitmapText "size" the fonts are registered with: fontSize = size × scale gives an exact ×scale. */
  size: 7,
  capHeight: 7,
  xHeight: 5,
  /** Row index of the baseline row (0-based, top down). */
  baselineRow: 6,
  /** Integer render scales the UX uses (ux/hud-layout.md §0). Never render at a fractional scale. */
  scales: [2, 3, 4, 6, 8],
  /** Width in logical px of n chars at scale s: advance·s·n − letterSpacing·s. */
  widthFormula: "6*s*n - s",
} as const;

/**
 * Outline plan. The outlined variants add a 1-font-px ring, 8-connected (diagonals included, so
 * diagonal strokes like / X V keep a closed dark edge; the art sprites use 4-connected, but text needs
 * the stronger local contrast of settings-and-a11y C8). Enclosed counters (B, 0, 8, @) fill with the
 * outline colour, which keeps them readable on any background.
 * Each outlined glyph cell is 7×9 and is drawn with xOffset −1 / yOffset −1, so the advance (6) and the
 * glyph-box top-left used by the UX layout are unchanged: the ring spills 1 px outside the box.
 * Neighbouring rings share the 1-px gap column; both are outline colour, so nothing overlaps a fill.
 */
export const FONT_OUTLINE = {
  px: 1,
  connectivity: 8,
  cellW: 7,
  cellH: 9,
  xOffset: -1,
  yOffset: -1,
} as const;

/**
 * The three baked variants. Colours are PALETTE chars from art/sprites.ts (so a palette retune flows
 * through), except '@', which is the pipeline mask colour: pure #ffffff, meant to be tinted at runtime
 * (white × tint = the exact tint colour, so tinted text stays on-palette).
 *   plain   – mask fill, no outline. Tint it: `w` labels on `p`, `Y` bank/cost numbers on `p`,
 *             `s` can't-afford costs on `p`, 50% alpha for disabled labels. Panels only.
 *   outline – `w` fill, `k` ring. Floaters, "CATCH IT!", every button label (bare `w` on `G` fails, 3.13:1),
 *             and all other text drawn over the stage.
 *   crit    – `Y` fill, `r` ring. Crit floaters "+N!" and Tap Frenzy floaters (style-guide §7).
 */
