def proof_density(font, font2, with_godot):
    """proofs/font-density2.png: every glyph at x4 on a k 4 device (Sevev 9 = 4-dp px, @2 = 2-dp px), and,
    with --godot, the real strings through TextServer in their real boxes. Returns (path, width report)."""
    grid = proof_density_glyphs(font, font2)
    pad, colw = 16, 0
    rows, lines_img, widths = [], None, []
    if with_godot:
        # layout: per line a caption, then the Sevev 9 box and the @2 box side by side (both the real box width)
        def n_lines(text, w):                        # greedy word wrap at x4, for the box height only
            n, cur = 1, 0
            for word in text.split(" "):
                ww = F.advance_of(font, word) * 4
                nxt = ww if cur == 0 else cur + 16 + ww
                if nxt > w and cur:
                    n, cur = n + 1, ww
                else:
                    cur = nxt
            return n
        colw = max(w for _, _, w, _, _ in DENSITY_LINES)
        y = 0
        spec = []
        for cap, text, w, fg, bg in DENSITY_LINES:
            h = 44 * n_lines(text, w) + 8
            spec.append({"text": text, "w": w, "fg": fg, "bg": bg, "cap": cap, "y": y + 22, "h": h,
                         "x": [pad, pad + colw + 2 * pad]})
            y += 22 + h + 12
        W, H = pad * 4 + 2 * colw, y
        tmp = tempfile.mkdtemp(prefix="ods-density-")
        for f in os.listdir(FONT_DEST):
            if f.startswith("sevev9") and f.endswith((".fnt", ".png", ".import")):
                shutil.copy(os.path.join(FONT_DEST, f), tmp)
        for f in os.listdir(tmp):
            if f.endswith(".import"):
                txt = open(os.path.join(tmp, f)).read()
                txt = "\n".join(l for l in txt.split("\n") if not l.startswith(("uid=", "path=", "dest_files=", "source_file=")))
                open(os.path.join(tmp, f), "w").write(txt)
        open(os.path.join(tmp, "project.godot"), "w").write(
            'config_version=5\n[application]\nconfig/name="density"\n[display]\nwindow/size/viewport_width=64\n'
            'window/size/viewport_height=64\n[rendering]\nrenderer/rendering_method="gl_compatibility"\n'
            'textures/canvas_textures/default_texture_filter=0\n')
        json.dump([{"canvasW": W, "canvasH": H}] + spec, open(os.path.join(tmp, "lines.json"), "w"), ensure_ascii=False)
        open(os.path.join(tmp, "density.gd"), "w").write(DENSITY_GD)
        godot(["--headless", "--path", tmp, "--import"])
        r = godot(["--path", tmp, "--rendering-driver", "opengl3", "-s", "res://density.gd"], timeout=120)
        out = os.path.join(tmp, "lines.png")
        if not os.path.exists(out):
            raise RuntimeError("density proof render failed:\n" + r.stdout[-3000:] + r.stderr[-3000:])
        fg_img = Image.open(out).convert("RGBA")
        lines_img = Image.new("RGBA", (W, H), (14, 10, 22, 255))
        for s in spec:
            for c in range(2):
                x = s["x"][c]
                lines_img.paste(Image.new("RGBA", (s["w"], s["h"]), s["bg"]), (x, s["y"]))
            _text(lines_img, font, s["cap"], pad, s["y"] - 18, 2, (245, 197, 66, 255))
            _text(lines_img, font, "SEVEV 9 @2", s["x"][1], s["y"] - 18, 2, (245, 197, 66, 255))
        lines_img.alpha_composite(fg_img)
        widths = json.load(open(os.path.join(tmp, "widths.json")))
        shutil.rmtree(tmp, ignore_errors=True)
    W = max(grid.width, lines_img.width if lines_img else 0) + 16
    H = 40 + grid.height + (lines_img.height + 40 if lines_img else 0)
    sheet = Image.new("RGBA", (W, H), (14, 10, 22, 255))
    _text(sheet, font, "SEVEV 9 (4 DP PX) | SEVEV 9 @2 (2 DP PX) - X4 LOGICAL ON A K 4 DEVICE, SAME BOXES", 8, 12, 2,
          (247, 244, 236, 255))
    sheet.alpha_composite(grid, (8, 40))
    if lines_img:
        sheet.alpha_composite(lines_img, (8, 40 + grid.height + 32))
    p = os.path.join(PROOFS, "font-density2.png")
    sheet.save(p)
    return p, widths


def _frame(tex, spec, i=0):
    """Frame i of a strip or grid (sprites.json layout; `frameMap` picks the texture cell)."""
    cols = spec.get("cols", spec.get("frames", 1))
    fw, fh = spec["frameW"], spec["frameH"]
    c = spec["frameMap"][i] if "frameMap" in spec else i
    x, y = (c % cols) * fw, (c // cols) * fh
    return tex.crop((x, y, x + fw, y + fh))


def pick(entry, k):
    """SpriteStrip.pick_variant in Python: the render (main or a `densities` alternate) with the largest
    density dividing k, merged over the main entry; the main render when none divides k."""
    best, best_d = entry, (entry.get("density", 1) if k % entry.get("density", 1) == 0 else 0)
    for dk, alt in entry.get("densities", {}).items():
        if k % int(dk) == 0 and int(dk) > best_d:
            best, best_d = {**{x: y for x, y in entry.items() if x != "densities"}, **alt, "density": int(dk)}, int(dk)
    return best


def proof_cast(manifest, Z=3, k=None, name="sprites-contact.png"):
    """Everything on one sheet at ART x Z (a density-d texture at Z/d per sprite px), so the cast's 3x
    detail and the 1x stage, props and UI sit on one grid, the way the renderer will draw them.
    k: draw each character and source as SpriteStrip picks it for device scale k (Z = k = 4: the d 2
    alternates, as a DPR-2 phone draws them)."""
    D_ = S.DEST
    load = lambda sid: Image.open(os.path.join(D_, sid + ".png")).convert("RGBA")
    up = lambda im, d: im.resize((im.width * Z // d, im.height * Z // d), Image.NEAREST)
    chars = {n: (pick(c, k) if k else c) for n, c in manifest["chars"].items()}
    per_row, cell_w, cell_h = 8, 90 * Z, 150 * Z
    rows = -(-len(chars) // per_row)
    W = 180 * Z + 8 * Z + per_row * cell_w
    Hh = max(320 * Z, rows * cell_h) + 60 * Z
    img = Image.new("RGBA", (W, Hh), (27, 20, 38, 255))
    img.alpha_composite(up(load(manifest["stages"]["balfour"]["sprite"]), 1), (0, 0))
    b = chars.get("bibi")
    if b:
        d = b["density"]
        fr = up(_frame(Image.open(os.path.join(D_, b["anims"]["idle"]["texture"])).convert("RGBA"), {**b, **b["anims"]["idle"]}), d)
        fx, fy = manifest["magicianFeet"]
        img.alpha_composite(fr, (fx * Z - b["anchor"][0] * Z // d, fy * Z - b["anchor"][1] * Z // d))
    for k, (n, c) in enumerate(chars.items()):
        d = c["density"]
        cx = 180 * Z + 8 * Z + (k % per_row) * cell_w + cell_w // 2
        base = (k // per_row) * cell_h + 112 * Z
        fr = up(_frame(Image.open(os.path.join(D_, c["anims"]["idle"]["texture"])).convert("RGBA"), {**c, **c["anims"]["idle"]}), d)
        img.alpha_composite(fr, (cx - c["anchor"][0] * Z // d, base - c["anchor"][1] * Z // d))   # feet on one baseline
        if "avatar" in c:
            av = up(load(c["avatar"]), 1)
            img.alpha_composite(av, (cx - av.width // 2, base + 2 * Z))
    x, y = 4 * Z, max(320 * Z, rows * cell_h) + 4 * Z
    for sid, s in sorted(manifest.get("sources", {}).items()):
        s = pick(s, k) if k else s
        strip = load(s["sprite"])
        for i in range(2):
            fr = up(_frame(strip, s, i), s.get("density", 1))
            img.alpha_composite(fr, (x, y))
            x += fr.width + Z
        x += 6 * Z
    for sid in manifest["props"].values():
        im = up(load(sid), 1)
        img.alpha_composite(im, (x, y))
        x += im.width + 4 * Z
    p = os.path.join(PROOFS, name)
    img.save(p)
    return p


def proof_stage(manifest, Z=6, density=None, char="bibi", anim="crit", frame=6):
    """A character on the stage at ART xZ, the way SpriteStrip picks it for k = Z: the main render
    (d 3 at x6: sprite px x2) or a `densities` alternate (d 2 at x4: sprite px x2)."""
    D_ = S.DEST
    st = Image.open(os.path.join(D_, manifest["stages"]["balfour"]["sprite"] + ".png")).convert("RGBA")
    img = st.resize((180 * Z, 320 * Z), Image.NEAREST)
    c = manifest["chars"][char]
    if density is not None and density != c["density"]:
        c = {**c, **c["densities"][str(density)]}
    d = c["density"]
    fr = _frame(Image.open(os.path.join(D_, c["anims"][anim]["texture"])).convert("RGBA"), {**c, **c["anims"][anim]}, frame)
    fr = fr.resize((fr.width * Z // d, fr.height * Z // d), Image.NEAREST)
    fx, fy = manifest["magicianFeet"]
    img.alpha_composite(fr, (fx * Z - c["anchor"][0] * Z // d, fy * Z - c["anchor"][1] * Z // d))
    p = os.path.join(PROOFS, f"stage-x{Z}-{char}" + (f"-d{d}" if density is not None else "") + ".png")
    img.save(p)
    return p


