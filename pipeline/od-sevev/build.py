def _text(img, font, text, x, y, scale, color=(255, 255, 255, 255)):
    """Proof-only LTR blitter (used for hex labels and Latin); Hebrew proofs go through Godot."""
    g, al, sp = font["glyphs"], font["aliases"], font["space"]
    for ch in text:
        cp = ord(ch)
        src = cp if cp in g else al.get(cp)
        if src in g:
            rows = g[src]
            for j, r in enumerate(rows):
                for i, c in enumerate(r):
                    if c == "#":
                        for dy in range(scale):
                            for dx in range(scale):
                                img.putpixel((x + (i) * scale + dx, y + j * scale + dy), color)
            x += (len(rows[0]) + 1) * scale
        else:
            x += (sp + 1) * scale


def proof_glyphs(font):
    g = font["glyphs"]
    cps = sorted(g)
    cols, cw, ch = 12, 58, 66
    rows = (len(cps) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cw + 8, rows * ch + 8), (42, 35, 64, 255))
    for k, cp in enumerate(cps):
        x, y = 4 + (k % cols) * cw, 4 + (k // cols) * ch
        for yy in range(y, y + ch - 4):
            for xx in range(x, x + cw - 4):
                img.putpixel((xx, yy), (27, 20, 38, 255))
        # the glyph at x4 with its advance box
        gx, gy = x + 6, y + 4
        w = len(g[cp][0])
        for j, r in enumerate(g[cp]):
            for i, c in enumerate(r):
                col = (247, 244, 236, 255) if c == "#" else ((60, 52, 84, 255) if 2 <= j <= 6 else (44, 38, 62, 255))
                for dy in range(4):
                    for dx in range(4):
                        img.putpixel((gx + i * 4 + dx, gy + j * 4 + dy), col)
        _text(img, font, f"{cp:04X}", x + 4, y + 44, 2, (245, 197, 66, 255))
    p = os.path.join(PROOFS, "font-glyphs.png")
    img.save(p)
    return p


def proof_density_glyphs(font, font2, dp=4, d=2):
    """Every glyph, Sevev 9 at `dp` device px per px beside Sevev 9 @2 at dp/d, in the same advance box
    (the box shaded, the body band a shade lighter): the two halves of a cell must cover the same area."""
    g1, g2 = font["glyphs"], font2["glyphs"]
    cps = sorted(g1)
    cols = 8
    cw = 2 * 10 * dp + 24          # two cells of up to 9 + 1 px (the widest pictograms)
    ch = 9 * dp + 26
    rows = -(-len(cps) // cols)
    img = Image.new("RGBA", (cols * cw + 8, rows * ch + 8), (14, 10, 22, 255))
    ink, box, band = (247, 244, 236, 255), (44, 38, 62, 255), (60, 52, 84, 255)

    def cell(rows_, x0, y0, p, dens):
        w = len(rows_[0])
        adv = w + dens
        for j in range(9 * dens):
            col = band if 2 * dens <= j < 7 * dens else box
            img.paste(col, (x0, y0 + j * p, x0 + adv * p, y0 + (j + 1) * p))
        for j, r in enumerate(rows_):
            for i, c in enumerate(r):
                if c == "#":
                    img.paste(ink, (x0 + i * p, y0 + j * p, x0 + (i + 1) * p, y0 + (j + 1) * p))

    for k, cp in enumerate(cps):
        x, y = 4 + (k % cols) * cw, 4 + (k // cols) * ch
        img.paste((27, 20, 38, 255), (x, y, x + cw - 4, y + ch - 4))
        cell(g1[cp], x + 4, y + 4, dp, 1)
        cell(g2[cp], x + 4 + 10 * dp + 8, y + 4, dp // d, d)
        _text(img, font, f"{cp:04X}", x + 4, y + 9 * dp + 6, 2, (245, 197, 66, 255))
    return img


