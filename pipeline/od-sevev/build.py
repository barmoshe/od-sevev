def log(msg):
    print(msg, flush=True)


def build_font():
    font = F.parse()
    for line in F.check(font):
        log("font: " + line)
    # content coverage: every glyph the game's strings use (keys starting with "_" are docs)
    have = set(font["glyphs"]) | set(font["aliases"]) | set(font["zeros"]) | {0x20, 0x0A}

    def walk(o, path):
        if isinstance(o, str):
            yield path, o
        elif isinstance(o, dict):
            for k, v in o.items():
                if not str(k).startswith("_"):
                    yield from walk(v, f"{path}.{k}")
        elif isinstance(o, list):
            for i, v in enumerate(o):
                yield from walk(v, f"{path}[{i}]")
    for rel in ("ux/ui-strings.json", "design/content.json"):
        fp = os.path.join(FORK, rel)
        if not os.path.exists(fp):
            continue
        miss = {}
        for path, s in walk(json.load(open(fp, encoding="utf-8")), ""):
            for ch in s:
                if ord(ch) not in have:
                    miss.setdefault(ch, path)
        log(f"font: {rel}: " + ("every character covered" if not miss else
            "WARN no glyph for " + ", ".join(f"U+{ord(c):04X} {c!r} (e.g. {p})" for c, p in miss.items())))
    os.makedirs(FONT_DEST, exist_ok=True)
    stats = []
    for name, outline in (("sevev9", False), ("sevev9_outline", True)):
        st = F.build(font, FONT_DEST, name, outline)
        S.write_import(os.path.join(FONT_DEST, name + ".fnt"), "font_data_bmfont", "FontFile", BMFONT_PARAMS)
        stats.append(st)
        log(f"font: {name}.fnt + .png page {st['page'][0]}x{st['page'][1]}, {st['chars']} chars")

    # Sevev 9 @2: the density-2 companion (same box at half the scale; every metric exactly 2x)
    font2 = F.parse(F.SOURCE_2X, density=2)
    for line in F.check(font2):
        log("font @2: " + line)
    st = F.build(font2, FONT_DEST, FONT_2X, False)
    S.write_import(os.path.join(FONT_DEST, FONT_2X + ".fnt"), "font_data_bmfont", "FontFile", BMFONT_PARAMS)
    # the page is embedded in the .fontdata: never import it as a texture of its own (as Sevev 9's pages)
    open(os.path.join(FONT_DEST, FONT_2X + ".png.import"), "w").write('[remap]\n\nimporter="skip"\n')
    stats.append(st)
    log(f"font: {FONT_2X}.fnt + .png page {st['page'][0]}x{st['page'][1]}, {st['chars']} chars")
    metric = F.check_companion(os.path.join(FONT_DEST, "sevev9.fnt"), os.path.join(FONT_DEST, FONT_2X + ".fnt"), 2)
    for line in metric:
        log("font: " + line)
    write_font_manifest(stats, metric)
    return font, font2, stats


FONT_2X = "sevev9@2"


def write_font_manifest(stats, metric):
    """game/assets/fonts/fonts.json: every cut with its density, so the engine picks a cut by density and
    draws it at (logical px per Sevev 9 px) / density. Generated; never hand-edited."""
    by = {st["name"]: st for st in stats}
    entry = lambda n, **kw: {"file": n + ".fnt", "density": by[n]["density"], "size": by[n]["size"],
                             "lineHeight": by[n]["lineHeight"], "base": by[n]["base"], "chars": by[n]["chars"], **kw}
    man = {
        "_doc": "Generated by pipeline/od-sevev/build.py (CONTRACT.md §6). density = font px per Sevev 9 px: a "
                "density-d cut is drawn at (the Sevev 9 scale) / d and covers exactly the same box, because every "
                "xadvance, the line height, the baseline and every ink box are d x Sevev 9's (checked at build: "
                "metricCheck). Layout, string budgets and the text lint measure with Sevev 9 and hold for every cut.",
        "fonts": {
            "sevev9": entry("sevev9", outline="sevev9_outline.fnt", role="display: the chunky cut"),
            "sevev9_outline": entry("sevev9_outline", companionOf="sevev9", role="display over art (baked ink ring)"),
            FONT_2X: entry(FONT_2X, companionOf="sevev9", role="reading text: the sharp cut (same box)"),
        },
        "metricCheck": metric,
    }
    json.dump(man, open(os.path.join(FONT_DEST, "fonts.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)


